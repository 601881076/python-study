########################## 解包列表或元组传参 ##########################
# 定义函数时，使用*args（变量不一定非要用args，比如写：*data也行），将收到的多个参数，打包成一个元组
# def test(*args):
#     print(f'我是test函数，我收到的参数是：{args}，参数类型是：{type(args)}')
#
# list1 = [100, 200, 300, 400]
# tuple1 = ('你好', '北京', '尚硅谷')
#
# # 函数调用时，正常传递：列表 或 元组，相当于将 list1当做一个元组传入到test函数中
# # test(list1) #
# test(tuple1) # 我是test函数，我收到的参数是：(('你好', '北京', '尚硅谷'),)，参数类型是：<class 'tuple'>
#
# # 函数调用时，使用*对：列表 或 元组进行解包后，再传递参数，
# # test(*list1)  # 此种写法相当于：test(100, 200, 300, 400)
# test(*tuple1)  # 此种写法相当于：test('你好', '北京', '尚硅谷'),输出 我是test函数，我收到的参数是：('你好', '北京', '尚硅谷')，参数类型是：<class 'tuple'>


