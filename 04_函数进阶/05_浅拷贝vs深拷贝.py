import copy

"""
为什么要拷贝?
● 赋值语句：b = a ，只是让b 指向和 a 一样的对象。
● 如果a和b指向的是一个可变对象，那通过b修改后，再通过a访问到的数据也是变化后的。
"""

"""
直接赋值
"""
# 在如下代码中：nums2 = nums1 不是复制！是两个变量指向同一个列表，并且修改任何一个，都会影响另一个
# nums1 : list[int] = [10, 20, 30, 40]
